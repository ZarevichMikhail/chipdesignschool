start:
    li      t4, 0x10010000     # базовый адрес для сохранения чисел Фибоначчи
    li      t2, 10              # количество чисел для вычисления
    li      t0, 1               # первое число Фибоначчи
    li      t1, 1               # второе число Фибоначчи
    sh      t0, (t4)            # сохраняем первое число
    addi    t4, t4, 2           # сдвигаем адрес на 2 байта (halfword)
    sh      t1, (t4)            # сохраняем второе число

fibonacci:
    mv      a0, t1              # сохраняем t1 во временный регистр
    add     t1, t0, t1          # t1 = t0 + t1 (следующее число)
    mv      t0, a0              # t0 = предыдущее t1
    addi    t2, t2, -1          # уменьшаем счетчик
    addi    t4, t4, 2           # сдвигаем адрес
    sh      t1, (t4)            # сохраняем следующее число
    bnez    t2, fibonacci       # повторяем, если счетчик не ноль