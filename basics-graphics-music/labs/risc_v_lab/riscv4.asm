start:
    li      t4, 0x10010000      # базовый адрес для чисел Фибоначчи
    li      t2, 10              # количество чисел для вычисления
    li      t3, 1               # константа для декремента
    addi    t4, t4, 0x4         # смещаем адрес на 4 байта (после двух начальных чисел)

fibonacci:
    lw      t0, -4(t4)          # загружаем предпоследнее число (на 4 байта назад)
    lw      t1, (t4)            # загружаем последнее число (по текущему адресу)
    mv      a0, t1              # сохраняем t1 во временный регистр
    add     t1, t0, t1          # t1 = t0 + t1 (следующее число)
    mv      t0, a0              # t0 = предыдущее t1
    sub     t2, t2, t3          # уменьшаем счетчик (t2 = t2 - 1)
    addi    t4, t4, 0x4         # увеличиваем адрес на 4 байта
    sw      t1, (t4)            # сохраняем новое число в память
    bnez    t2, fibonacci       # повторяем, если счетчик не ноль

