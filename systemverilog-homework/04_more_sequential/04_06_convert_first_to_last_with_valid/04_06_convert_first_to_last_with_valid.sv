module conv_first_to_last_no_ready
# (
    parameter width = 8
)
(
    input                clock,
    input                reset,

    input                up_valid,
    input                up_first,
    input  [width - 1:0] up_data,

    output               down_valid,
    output               down_last,
    output [width - 1:0] down_data
);
    // Task:
    // Implement a module that converts 'first' input status signal
    // to the 'last' output status signal.
    //
    // See README for full description of the task with timing diagram.


    // Смысл этого задания тоже сначала не понял. 

    // Передаются данные. Есть сигнал первого элемента и последнего. 
    // Зная, какой элемент пришёл первым, мы не можем сказать, 
    // какой элемент будет последним

    // Можно узнать, что предыдущий элемент был последним
    // Только если вместе с текущим пришёл сигнал up_first 


    /*
     * Смысл работы: Задержка потока на 1 такт для определения конца пакета.
     * Мы узнаем, что элемент был LAST только когда видим FIRST следующего пакета.
     *
     * Таблица переходов (Timing Diagram):
     * +-------+---------+--------+----------+-----------+-----------+----------+-----------+---------------------------------+
     * | Cycle | up_data | up_vld | up_first |data_buffer| down_data | down_vld | down_last | Комментарий                     |
     * +-------+---------+--------+----------+-----------+-----------+----------+-----------+---------------------------------+
     * |   1   |   A1    |   1    |    1     |    'x     |    'x     |    0     |     0     | A1 заходит в буфер              |
     * |   2   |   A2    |   1    |    0     |    A1     |    A1     |    1     |     0     | A2 выталкивает A1 (не LAST)     |
     * |   3   |   B1    |   1    |    1     |    A2     |    A2     |    1     |     1     | B1(FIRST) выталкивает A2(LAST)  |
     * |   4   |   --    |   0    |    --    |    B1     |    --     |    0     |     0     | Пауза, B1 ждет в буфере         |
     * +-------+---------+--------+----------+-----------+-----------+----------+-----------+---------------------------------+
     *
     * ВНИМАНИЕ: Последний элемент последнего пакета (B1) "зависает" в буфере до появления 
     * новых данных, так как мы не знаем, будет ли за ним продолжение или нет.
     */

    // Буфер для хранения выходных элементов
    logic [width - 1:0] data_buffer;


    // Сигнал того, то началась новая последовательность элементов
    // Значит
    logic is_next_sequence_started;

    // Выходные данные — это всегда данные из буфера, которые идут с задержкой
    assign down_data = data_buffer;

    // Выход валиден только если в буфере что-то есть И началось новое слово,
    assign down_valid = up_valid && is_next_sequence_started;

    // Если новое слово является началом следующего пакета (up_first),
    // то выталкиваемое из буфера слово было концом предыдущего пакета.
    assign down_last = up_first;

    always_ff @(posedge clock) begin
        if (reset) begin
            is_next_sequence_started  <= 1'b0;
            data_buffer <= '0;
        end
        else if (up_valid == 1) begin
            // Сохраняем текущее слово в буфер для выдачи в следующем валидном такте
            is_next_sequence_started  <= 1'b1;
            data_buffer <= up_data;
        end
    end



endmodule
